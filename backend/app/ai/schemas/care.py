"""
Pydantic schemas for AI care & treatment analysis.

These define the EXACT structure the LLM must return. They serve as the
validation firewall between free-form LLM output and the database.

Usage:
    raw_json = json.loads(llm_response_text)
    validated = AIAnalysisResponse.model_validate(raw_json)
    # Only `validated` is used for DB operations — never raw_json directly.
"""

from typing import Literal
from pydantic import BaseModel, Field


# ── Care Plan ────────────────────────────────────────────────────

class CareDetails(BaseModel):
    """Personalized care instructions for the plant."""
    watering: str = Field(
        ..., min_length=1, max_length=1000,
        description="Watering schedule and amount"
    )
    sunlight: str = Field(
        ..., min_length=1, max_length=1000,
        description="Light requirements"
    )
    temperature: str = Field(
        ..., min_length=1, max_length=1000,
        description="Ideal temperature range"
    )
    humidity: str = Field(
        ..., min_length=1, max_length=1000,
        description="Humidity requirements"
    )
    soil: str = Field(
        ..., min_length=1, max_length=1000,
        description="Soil type and composition"
    )
    fertilization: str = Field(
        ..., min_length=1, max_length=1000,
        description="Fertilization schedule and type"
    )
    pruning: str = Field(
        ..., min_length=1, max_length=1000,
        description="Pruning instructions"
    )


# ── Problem Detection ───────────────────────────────────────────

PROBLEM_CATEGORIES = Literal[
    "healthy",
    "fungal_disease",
    "bacterial_disease",
    "viral_disease",
    "pest_infestation",
    "nutrient_deficiency",
    "environmental_stress",
    "overwatering",
    "underwatering",
    "root_rot",
    "sunburn",
    "other",
]

SEVERITY_LEVELS = Literal["none", "low", "medium", "high", "critical"]


class ProblemDetails(BaseModel):
    """Diagnosis of any detected problems."""
    detected: bool = Field(
        ..., description="Whether a problem was detected"
    )
    name: str = Field(
        default="", max_length=255,
        description="Name of the detected problem"
    )
    category: PROBLEM_CATEGORIES = Field(
        default="healthy",
        description="Category of the problem"
    )
    severity: SEVERITY_LEVELS = Field(
        default="none",
        description="Severity level of the problem"
    )
    description: str = Field(
        default="", max_length=2000,
        description="Detailed description of the problem"
    )


# ── Treatment Plan ──────────────────────────────────────────────

class TreatmentDetails(BaseModel):
    """Treatment plan if a problem is detected."""
    required: bool = Field(
        ..., description="Whether treatment is needed"
    )
    product_category: str = Field(
        default="", max_length=100,
        description="Category of treatment product (e.g., fungicide, pesticide)"
    )
    recommended_actions: list[str] = Field(
        default_factory=list,
        description="Step-by-step treatment actions"
    )
    frequency: str = Field(
        default="", max_length=500,
        description="How often to apply treatment"
    )
    estimated_duration: str = Field(
        default="", max_length=500,
        description="Expected duration of treatment"
    )
    precautions: list[str] = Field(
        default_factory=list,
        description="Safety precautions during treatment"
    )
    instructions: str = Field(
        default="", max_length=2000,
        description="Detailed treatment instructions"
    )


# ── Plant Care Plan (Graph & LLM Contract) ──────────────────────

class PlantCarePlan(BaseModel):
    """
    Personalized plant care plan generated by the plant_analysis node.
    """
    summary: str = Field(
        ..., min_length=1, max_length=3000,
        description="Comprehensive summary of the plant's health and general care strategy"
    )
    watering: str = Field(
        ..., min_length=1, max_length=1000,
        description="Watering frequency, method, and moisture guidelines"
    )
    sunlight: str = Field(
        ..., min_length=1, max_length=1000,
        description="Light intensity, exposure duration, and placement recommendations"
    )
    humidity: str = Field(
        ..., min_length=1, max_length=1000,
        description="Target humidity level and misting/humidifier advice"
    )
    temperature: str = Field(
        ..., min_length=1, max_length=1000,
        description="Optimal day/night temperature range and thermal protection"
    )
    soil: str = Field(
        ..., min_length=1, max_length=1000,
        description="Recommended soil mix, drainage, and aeration specifications"
    )
    fertilization: str = Field(
        ..., min_length=1, max_length=1000,
        description="Fertilizer type (NPK/organic), dilution ratio, and schedule"
    )
    pruning: str = Field(
        ..., min_length=1, max_length=1000,
        description="Trimming, deadheading, and maintenance instructions"
    )
    general_care: list[str] = Field(
        default_factory=list,
        description="General care tips, seasonal adjustments, and prevention guidelines"
    )


# ── Treatment Decision (Graph & LLM Contract) ───────────────────

REQUIRED_PRODUCT_CATEGORIES = Literal[
    "fertilizer",
    "fungicide",
    "pest_control",
    "soil_amendment",
    "potting_mix",
    "plant_care",
    "none",
]


class TreatmentDecisionOutput(BaseModel):
    """
    Decision output determining WHAT category of product/treatment is needed.
    The LLM never invents real products, prices, or inventory.
    """
    treatment_required: bool = Field(
        ..., description="Whether active intervention/treatment is required"
    )
    problem_category: PROBLEM_CATEGORIES = Field(
        default="healthy",
        description="Identified problem category requiring treatment"
    )
    required_product_category: REQUIRED_PRODUCT_CATEGORIES = Field(
        default="none",
        description="Category of product required (e.g., fungicide, fertilizer)"
    )
    treatment_reason: str = Field(
        default="", max_length=1000,
        description="Clinical rationale for the treatment decision"
    )
    treatment_confidence: float = Field(
        default=0.9, ge=0.0, le=1.0,
        description="Confidence score for the treatment necessity"
    )
    recommended_actions: list[str] = Field(
        default_factory=list,
        description="Step-by-step action items for the user"
    )
    precautions: list[str] = Field(
        default_factory=list,
        description="Safety precautions and environmental considerations"
    )


# ── Top-Level Response ──────────────────────────────────────────

class AIAnalysisResponse(BaseModel):
    """
    Top-level schema the LLM MUST return.

    This is the validation contract. Every field is validated through
    Pydantic before the result touches the database. If the LLM returns
    data that doesn't match this schema, the request fails with a
    structured error rather than corrupting the database.
    """
    summary: str = Field(
        ..., min_length=1, max_length=3000,
        description="Overall summary of plant condition and care needs"
    )
    care: CareDetails
    problem: ProblemDetails
    treatment: TreatmentDetails

    model_config = {"extra": "ignore"}
