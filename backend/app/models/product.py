"""
Product models: Category, Product, and ProductCompatibility.

Category — product grouping (Fertilizer, Fungicide, etc.)
Product — an actual purchasable product with real data
ProductCompatibility — links products to plant species and problem categories
"""

import uuid
from datetime import datetime, timezone

from sqlalchemy import (
    String, Text, Float, Integer, Boolean, ForeignKey,
    DateTime, Numeric, Index, UUID,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, TimestampMixin


class Category(Base):
    """Product category (e.g., Fertilizer, Fungicide, Pest Control)."""

    __tablename__ = "categories"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    name: Mapped[str] = mapped_column(
        String(100), nullable=False, unique=True
    )
    slug: Mapped[str] = mapped_column(
        String(100), nullable=False, unique=True, index=True
    )
    description: Mapped[str | None] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    # Relationships
    products = relationship(
        "Product", back_populates="category", cascade="all, delete-orphan"
    )

    def __repr__(self) -> str:
        return f"<Category(id={self.id}, name={self.name})>"


class Product(TimestampMixin, Base):
    """
    A real, purchasable product in the Plantify catalog.

    IMPORTANT: Products are NEVER generated by the AI. They are seeded
    or created by admins. The AI only determines WHAT TYPE of product
    is needed; the recommendation pipeline selects WHICH product.
    """

    __tablename__ = "products"

    name: Mapped[str] = mapped_column(String(255), nullable=False)
    description: Mapped[str | None] = mapped_column(Text, nullable=True)
    category_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("categories.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    price: Mapped[float] = mapped_column(
        Numeric(10, 2), nullable=False
    )
    image_url: Mapped[str | None] = mapped_column(
        String(500), nullable=True
    )
    stock: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0
    )
    brand: Mapped[str | None] = mapped_column(
        String(100), nullable=True
    )
    usage_instructions: Mapped[str | None] = mapped_column(
        Text, nullable=True
    )
    active: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=True
    )
    is_seed_data: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False,
        doc="True if this product was inserted by the seed script (dev/test data).",
    )

    # Relationships
    category = relationship("Category", back_populates="products")
    compatibilities = relationship(
        "ProductCompatibility",
        back_populates="product",
        cascade="all, delete-orphan",
    )

    __table_args__ = (
        Index("ix_products_category_active", "category_id", "active"),
    )

    def __repr__(self) -> str:
        return f"<Product(id={self.id}, name={self.name}, price={self.price})>"


class ProductCompatibility(Base):
    """
    Maps a product to the plant species and/or problem categories it's suitable for.

    - If plant_species is NULL → product works for ALL species.
    - problem_category matches the PROBLEM_CATEGORIES Literal from ai/schemas/care.py.
    """

    __tablename__ = "product_compatibilities"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    product_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("products.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    plant_species: Mapped[str | None] = mapped_column(
        String(255), nullable=True,
        doc="NULL means compatible with all species.",
    )
    problem_category: Mapped[str] = mapped_column(
        String(50), nullable=False,
        doc="Must match a value from PROBLEM_CATEGORIES.",
    )

    # Relationships
    product = relationship("Product", back_populates="compatibilities")

    __table_args__ = (
        Index(
            "ix_product_compat_problem_species",
            "problem_category",
            "plant_species",
        ),
    )

    def __repr__(self) -> str:
        return (
            f"<ProductCompatibility(product_id={self.product_id}, "
            f"problem={self.problem_category}, species={self.plant_species})>"
        )
